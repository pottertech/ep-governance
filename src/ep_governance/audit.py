def _utc_now_iso() -> str:
    """Return the current UTC timestamp as ISO 8601 with microseconds and Z suffix.

    Format: YYYY-MM-DDTHH:MM:SS.ffffffZ
    """
    dt = datetime.now(UTC)
    return dt.strftime("%Y-%m-%dT%H:%M:%S.%f") + "Z"


def _dump_json(obj: dict[str, Any]) -> str:
    """Serialise event_data to a JSON string for storage.

    Uses canonical_json so the stored representation is deterministic.
    """
    return canonical_json(obj)


def _load_json(s: str | bytes | None) -> dict[str, Any]:
    """Parse event_data from a stored JSON string back to a dict."""
    if s is None:
        return {}
    if isinstance(s, (bytes, bytearray)):
        s = s.decode("utf-8")
    import json

    return json.loads(s)
